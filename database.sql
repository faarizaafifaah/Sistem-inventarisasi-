-- =====================================================
-- RESET DATABASE SISTEM ASET
-- =====================================================

DROP TABLE IF EXISTS pelepasan_aset CASCADE;
DROP TABLE IF EXISTS pelepasan CASCADE;
DROP TABLE IF EXISTS aset CASCADE;
DROP TABLE IF EXISTS kategori CASCADE;


-- =====================================================
-- 1. TABEL KATEGORI
-- =====================================================

CREATE TABLE kategori (
    id_kategori BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama_kategori VARCHAR(100) NOT NULL UNIQUE
);


-- =====================================================
-- 2. TABEL ASET
-- =====================================================

CREATE TABLE aset (
    id_aset BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    id_kategori BIGINT NOT NULL,

    kode_aset VARCHAR(50) NOT NULL UNIQUE,

    nama_aset VARCHAR(150) NOT NULL,

    lokasi VARCHAR(100) NOT NULL,

    tanggal_perolehan DATE NOT NULL,

    harga_perolehan NUMERIC(15,2) NOT NULL DEFAULT 0,

    kondisi VARCHAR(30) NOT NULL
        CHECK (kondisi IN (
            'Baik',
            'Rusak Ringan',
            'Rusak Berat'
        )),

    status_aset VARCHAR(30) NOT NULL DEFAULT 'Aktif'
        CHECK (status_aset IN (
            'Aktif',
            'Tidak Aktif',
            'Dilepas'
        )),

    CONSTRAINT fk_aset_kategori
        FOREIGN KEY (id_kategori)
        REFERENCES kategori(id_kategori)
);


-- =====================================================
-- 3. TABEL PELEPASAN
-- =====================================================

CREATE TABLE pelepasan (
    id_pelepasan BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    id_aset BIGINT NOT NULL UNIQUE,

    tanggal_pelepasan DATE NOT NULL,

    alasan VARCHAR(100) NOT NULL,

    nilai_pelepasan NUMERIC(15,2) NOT NULL DEFAULT 0,

    keterangan TEXT,

    CONSTRAINT fk_pelepasan_aset
        FOREIGN KEY (id_aset)
        REFERENCES aset(id_aset)
        ON DELETE CASCADE
);


